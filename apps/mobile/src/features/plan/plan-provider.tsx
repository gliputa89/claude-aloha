import { createContext, use, useCallback, useEffect, useRef, useState, type PropsWithChildren } from 'react';

import { fetchActivePlan, generatePlan, type ActivePlan, type PlanSession } from '@/features/plan/api';
import { syncStrava } from '@/features/strava/api';

export type PlanState =
  | { kind: 'loading' }
  | { kind: 'generating' }
  | { kind: 'ready'; plan: ActivePlan }
  | { kind: 'failed' }
  | { kind: 'loadFailed' };

type PlanContextValue = {
  state: PlanState;
  /** Ponowne wczytanie (np. pociągnięcie w dół). */
  reload: () => Promise<void>;
  /** Sam plan z bazy, bez pytania Stravy (np. po odpowiedzi „to był ten trening?”). */
  refresh: () => Promise<void>;
  /** Ponowne ułożenie planu po nieudanej próbie albo po zmianie celu (`keepLevel` – poziom z przeglądów zostaje). */
  generate: (options?: { keepLevel?: boolean }) => Promise<void>;
};

const PlanContext = createContext<PlanContextValue>({
  state: { kind: 'loading' },
  reload: async () => {},
  refresh: async () => {},
  generate: async () => {},
});

/** Jeden wspólny plan dla wszystkich zakładek – wczytany raz, odświeżany na żądanie. */
export function PlanProvider({ children }: PropsWithChildren) {
  const [state, setState] = useState<PlanState>({ kind: 'loading' });
  const autoGenerated = useRef(false);

  const generate = useCallback(async (options: { keepLevel?: boolean } = {}) => {
    setState({ kind: 'generating' });
    try {
      await generatePlan(options);
      const plan = await fetchActivePlan();
      setState(plan ? { kind: 'ready', plan } : { kind: 'failed' });
    } catch {
      setState({ kind: 'failed' });
    }
  }, []);

  const reload = useCallback(async () => {
    try {
      // Pociągnięcie w dół: najpierw nowe biegi ze Stravy, potem plan już z odhaczonymi treningami.
      await syncStrava(true);
      const plan = await fetchActivePlan();
      if (plan) {
        setState({ kind: 'ready', plan });
      } else if (!autoGenerated.current) {
        autoGenerated.current = true;
        await generate();
      } else {
        setState({ kind: 'failed' });
      }
    } catch {
      setState({ kind: 'loadFailed' });
    }
  }, [generate]);

  const refresh = useCallback(async () => {
    const plan = await fetchActivePlan().catch(() => null);
    if (plan) setState({ kind: 'ready', plan });
  }, []);

  // Pierwsze wczytanie: stan zmieniamy dopiero w callbacku zapytania.
  useEffect(() => {
    let active = true;
    fetchActivePlan()
      .then((plan) => {
        if (!active) return;
        if (plan) {
          setState({ kind: 'ready', plan });
          // Plan pokazujemy od razu; biegi ze Stravy dociągamy w tle (odhaczone treningi i pytania o przesunięte).
          syncStrava()
            .then(() => fetchActivePlan())
            .then((fresh) => active && fresh && setState({ kind: 'ready', plan: fresh }))
            .catch(() => {});
        } else {
          // Po ankiecie plan powstaje od razu; jeśli się nie udało (np. brak sieci) – próbujemy raz sami.
          autoGenerated.current = true;
          generate();
        }
      })
      .catch(() => active && setState({ kind: 'loadFailed' }));
    return () => {
      active = false;
    };
  }, [generate]);

  return <PlanContext value={{ state, reload, refresh, generate }}>{children}</PlanContext>;
}

export function usePlan() {
  return use(PlanContext);
}

/** Wszystkie treningi planu w kolejności dat. */
export function allSessions(plan: ActivePlan): PlanSession[] {
  return plan.weeks.flatMap((w) => w.sessions);
}

/** Treningi pogrupowane po dacie `YYYY-MM-DD`. */
export function sessionsByDate(plan: ActivePlan) {
  const map = new Map<string, PlanSession[]>();
  for (const s of allSessions(plan)) {
    const list = map.get(s.scheduled_on);
    if (list) list.push(s);
    else map.set(s.scheduled_on, [s]);
  }
  return map;
}
