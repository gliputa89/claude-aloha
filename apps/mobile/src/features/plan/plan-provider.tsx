import { createContext, use, useCallback, useEffect, useRef, useState, type PropsWithChildren } from 'react';

import { fetchActivePlan, generatePlan, type ActivePlan, type PlanSession } from '@/features/plan/api';
import { syncHealth } from '@/features/health/api';
import { syncStrava } from '@/features/strava/api';
import { readCache, writeCache } from '@/lib/data-cache';
import { useAuth } from '@/providers/auth-provider';

export type PlanState =
  | { kind: 'loading' }
  | { kind: 'generating' }
  | { kind: 'ready'; plan: ActivePlan }
  | { kind: 'failed' }
  | { kind: 'loadFailed' };

type PlanContextValue = {
  state: PlanState;
  /** Pierwsze dociągnięcie biegów ze Stravy po starcie już się skończyło (z wynikiem albo bez). */
  synced: boolean;
  /** Ponowne wczytanie (np. pociągnięcie w dół). */
  reload: () => Promise<void>;
  /** Sam plan z bazy, bez pytania Stravy (np. po odpowiedzi „to był ten trening?”). */
  refresh: () => Promise<void>;
  /** Ponowne ułożenie planu po nieudanej próbie albo po zmianie celu (`keepLevel` – poziom z przeglądów zostaje). */
  generate: (options?: { keepLevel?: boolean }) => Promise<void>;
};

const PlanContext = createContext<PlanContextValue>({
  state: { kind: 'loading' },
  synced: false,
  reload: async () => {},
  refresh: async () => {},
  generate: async () => {},
});

/**
 * Jeden wspólny plan dla wszystkich zakładek – wczytany raz, odświeżany na żądanie.
 * Ostatni plan jest zapamiętany na telefonie: ekrany pokazują go od razu, a świeży przychodzi w tle.
 */
export function PlanProvider({ children }: PropsWithChildren) {
  const userId = useAuth().session?.user.id ?? null;
  const [state, setStateRaw] = useState<PlanState>(() => {
    const cached = readCache<ActivePlan>('plan', userId);
    return cached ? { kind: 'ready', plan: cached } : { kind: 'loading' };
  });
  const [synced, setSynced] = useState(false);
  const autoGenerated = useRef(false);
  /** Plan z pamięci telefonu już na ekranie – błąd sieci go nie zasłania. */
  const hasPlan = useRef(state.kind === 'ready');

  // Każdy wczytany plan trafia też do pamięci telefonu.
  const setState = useCallback(
    (next: PlanState) => {
      if (next.kind === 'ready') {
        hasPlan.current = true;
        writeCache('plan', userId, next.plan);
      }
      setStateRaw(next);
    },
    [userId],
  );

  const generate = useCallback(async (options: { keepLevel?: boolean } = {}) => {
    setState({ kind: 'generating' });
    try {
      await generatePlan(options);
      const plan = await fetchActivePlan();
      setState(plan ? { kind: 'ready', plan } : { kind: 'failed' });
    } catch {
      setState({ kind: 'failed' });
    }
  }, [setState]);

  const reload = useCallback(async () => {
    try {
      // Pociągnięcie w dół: najpierw nowe biegi ze Stravy i z Apple Zdrowie, potem plan już z odhaczonymi treningami.
      await Promise.all([syncStrava(true), syncHealth(true)]);
      const plan = await fetchActivePlan();
      if (plan) {
        setState({ kind: 'ready', plan });
      } else if (!autoGenerated.current) {
        autoGenerated.current = true;
        await generate();
      } else {
        setState({ kind: 'failed' });
      }
    } catch {
      // Bez sieci zostaje plan, który już jest na ekranie.
      if (!hasPlan.current) setState({ kind: 'loadFailed' });
    }
  }, [generate, setState]);

  const refresh = useCallback(async () => {
    const plan = await fetchActivePlan().catch(() => null);
    if (plan) setState({ kind: 'ready', plan });
  }, [setState]);

  // Pierwsze wczytanie: stan zmieniamy dopiero w callbacku zapytania.
  useEffect(() => {
    let active = true;
    fetchActivePlan()
      .then((plan) => {
        if (!active) return;
        if (plan) {
          setState({ kind: 'ready', plan });
          // Plan pokazujemy od razu; biegi ze Stravy i z Apple Zdrowie dociągamy w tle (odhaczone treningi i pytania o przesunięte).
          Promise.all([syncStrava(), syncHealth()])
            .then(() => fetchActivePlan())
            .then((fresh) => active && fresh && setState({ kind: 'ready', plan: fresh }))
            .catch(() => {})
            .finally(() => active && setSynced(true));
        } else {
          // Po ankiecie plan powstaje od razu; jeśli się nie udało (np. brak sieci) – próbujemy raz sami.
          writeCache('plan', userId, null);
          autoGenerated.current = true;
          generate();
        }
      })
      .catch(() => {
        // Bez sieci zostaje plan z pamięci telefonu (jeśli jest); Strava i tak by się nie dociągnęła.
        if (!active) return;
        setSynced(true);
        if (!hasPlan.current) setState({ kind: 'loadFailed' });
      });
    return () => {
      active = false;
    };
    // Tylko pierwsze wczytanie – `setState` zależy od konta, a konto w tej części aplikacji się nie zmienia.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [generate]);

  return <PlanContext value={{ state, synced, reload, refresh, generate }}>{children}</PlanContext>;
}

export function usePlan() {
  return use(PlanContext);
}

/** Wszystkie treningi planu w kolejności dat. */
export function allSessions(plan: ActivePlan): PlanSession[] {
  return plan.weeks.flatMap((w) => w.sessions);
}

/** Treningi pogrupowane po dacie `YYYY-MM-DD`. */
export function sessionsByDate(plan: ActivePlan) {
  const map = new Map<string, PlanSession[]>();
  for (const s of allSessions(plan)) {
    const list = map.get(s.scheduled_on);
    if (list) list.push(s);
    else map.set(s.scheduled_on, [s]);
  }
  return map;
}
