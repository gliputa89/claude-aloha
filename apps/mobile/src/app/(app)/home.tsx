import { useCallback, useEffect, useRef, useState } from 'react';
import { ActivityIndicator, RefreshControl, ScrollView, StyleSheet, View } from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';

import { Mark } from '@/components/brand/mark';
import { SessionRow } from '@/components/plan/session-row';
import { Button } from '@/components/ui/button';
import { Notice } from '@/components/ui/notice';
import { Text } from '@/components/ui/text';
import { radius, space } from '@/constants/theme';
import { todayIso } from '@/features/onboarding/time';
import { fetchActivePlan, generatePlan, type ActivePlan } from '@/features/plan/api';
import { useColors } from '@/hooks/use-colors';
import { useT } from '@/hooks/use-t';
import { signOut } from '@/lib/auth';
import { useAuth } from '@/providers/auth-provider';

type State =
  | { kind: 'loading' }
  | { kind: 'generating' }
  | { kind: 'ready'; plan: ActivePlan }
  | { kind: 'failed' }
  | { kind: 'loadFailed' };

/** Ekran główny (tymczasowo): powitanie + pierwsze 2 tygodnie planu. Docelowo „Dzisiaj” wg makiet. */
export default function HomeScreen() {
  const t = useT();
  const c = useColors();
  const { profile } = useAuth();
  const [state, setState] = useState<State>({ kind: 'loading' });
  const [refreshing, setRefreshing] = useState(false);
  const [signingOut, setSigningOut] = useState(false);
  const autoGenerated = useRef(false);
  const today = todayIso();

  const generate = useCallback(async () => {
    setState({ kind: 'generating' });
    try {
      await generatePlan();
      const plan = await fetchActivePlan();
      setState(plan ? { kind: 'ready', plan } : { kind: 'failed' });
    } catch {
      setState({ kind: 'failed' });
    }
  }, []);

  const load = useCallback(async () => {
    try {
      const plan = await fetchActivePlan();
      if (plan) {
        setState({ kind: 'ready', plan });
      } else if (!autoGenerated.current) {
        // Po ankiecie plan powstaje od razu; jeśli się nie udało (np. brak sieci) – próbujemy raz sami.
        autoGenerated.current = true;
        await generate();
      } else {
        setState({ kind: 'failed' });
      }
    } catch {
      setState({ kind: 'loadFailed' });
    }
  }, [generate]);

  // Pierwsze wczytanie: stan zmieniamy dopiero w callbacku zapytania.
  useEffect(() => {
    let active = true;
    fetchActivePlan()
      .then((plan) => {
        if (!active) return;
        if (plan) {
          setState({ kind: 'ready', plan });
        } else {
          // Po ankiecie plan powstaje od razu; jeśli się nie udało (np. brak sieci) – próbujemy raz sami.
          autoGenerated.current = true;
          generate();
        }
      })
      .catch(() => active && setState({ kind: 'loadFailed' }));
    return () => {
      active = false;
    };
  }, [generate]);

  const onRefresh = async () => {
    setRefreshing(true);
    await load();
    setRefreshing(false);
  };

  const name = profile?.display_name;

  return (
    <SafeAreaView edges={['top', 'left', 'right']} style={[styles.flex, { backgroundColor: c.background }]}>
      <ScrollView
        contentContainerStyle={styles.content}
        refreshControl={<RefreshControl refreshing={refreshing} onRefresh={onRefresh} tintColor={c.action} />}>
        <View style={styles.header}>
          <View style={[styles.avatar, { backgroundColor: c.surfaceBrand }]}>
            <Mark size={36} wave="textOnBrand" />
          </View>
          <Text variant="title" accessibilityRole="header">
            {name ? t('home.greeting', { name }) : t('home.greetingNoName')}
          </Text>
          <Text color="textMuted">{t('plan.subtitle')}</Text>
        </View>

        {state.kind === 'loading' || state.kind === 'generating' ? (
          <View style={styles.center}>
            <ActivityIndicator color={c.action} size="large" />
            {state.kind === 'generating' ? <Text color="textMuted">{t('plan.generating')}</Text> : null}
          </View>
        ) : null}

        {state.kind === 'failed' ? (
          <View style={styles.block}>
            <Notice message={t('plan.failed')} />
            <Button label={t('plan.retry')} onPress={generate} />
          </View>
        ) : null}

        {state.kind === 'loadFailed' ? (
          <View style={styles.block}>
            <Notice message={t('plan.loadFailed')} />
            <Button variant="secondary" label={t('plan.retry')} onPress={load} />
          </View>
        ) : null}

        {state.kind === 'ready'
          ? state.plan.weeks.map((week) => (
              <View key={week.id} style={styles.week}>
                <Text variant="heading" accessibilityRole="header">
                  {t('plan.week', { n: week.week_index + 1 })}
                </Text>
                {week.sessions.map((s) => (
                  <SessionRow key={s.id} session={s} today={s.scheduled_on === today} />
                ))}
              </View>
            ))
          : null}

        <Button
          variant="plain"
          label={t('home.signOut')}
          loading={signingOut}
          onPress={async () => {
            setSigningOut(true);
            await signOut();
          }}
        />
      </ScrollView>
    </SafeAreaView>
  );
}

const styles = StyleSheet.create({
  flex: { flex: 1 },
  content: { paddingHorizontal: space[5], paddingTop: space[6], paddingBottom: space[8], gap: space[6] },
  header: { gap: space[2] },
  avatar: {
    width: 52,
    height: 52,
    borderRadius: radius.pill,
    alignItems: 'center',
    justifyContent: 'center',
    marginBottom: space[2],
  },
  center: { alignItems: 'center', gap: space[3], paddingVertical: space[8] },
  block: { gap: space[3] },
  week: { gap: space[3] },
});
